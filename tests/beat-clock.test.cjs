'use strict';
const test=require('node:test');
const assert=require('node:assert/strict');
const Beat=require('../src/beat-clock.js');
test('BPM and quantization inputs are bounded and backward compatible',()=>{
 assert.equal(Beat.normalizeBpm(37),40);
 assert.equal(Beat.normalizeBpm(330),240);
 assert.equal(Beat.normalizeBpm(123.8),124);
 assert.equal(Beat.normalizeBpm(Infinity),120);
 assert.equal(Beat.normalizeBpm('145'),120);
 assert.equal(Beat.normalizeQuantize('unexpected'),'off');
 assert.deepEqual(Beat.QUANTIZATIONS,['off','quarter','beat','two','bar']);
 assert.equal(Beat.beatDuration(120),500);
 assert.equal(Beat.intervalMs(120,'off'),0);
 assert.equal(Beat.intervalMs(120,'quarter'),125);
 assert.equal(Beat.intervalMs(120,'beat'),500);
 assert.equal(Beat.intervalMs(120,'two'),1000);
 assert.equal(Beat.intervalMs(120,'bar'),2000);
});
test('beat-quantized launches target the NEXT future boundary',()=>{
 assert.equal(Beat.nextBoundary(0,0,120,'beat'),500);
 assert.equal(Beat.nextBoundary(500,0,120,'beat'),1000);
 assert.equal(Beat.nextBoundary(501,0,120,'beat'),1000);
 assert.equal(Beat.nextBoundary(130,0,120,'quarter'),250);
 assert.equal(Beat.nextBoundary(520,100,120,'two'),1100);
 assert.equal(Beat.nextBoundary(0,0,120,'off'),0);
 assert.equal(Beat.nextBoundary(37,0,120,'off'),37);
 assert.equal(Beat.phase(0,0,120),0);
 assert.equal(Beat.phase(250,0,120),.5);
 assert.equal(Beat.phase(750,0,120),.5);
});
test('clock retains BPM and quantization, rephases and supports Tap Tempo',()=>{
 const clock=Beat.createClock({bpm:132,quantize:'beat',origin:100});
 assert.equal(clock.bpm,132);assert.equal(clock.quantize,'beat');
 clock.setBpm(150,1000);
 assert.equal(clock.origin,1000);
 assert.equal(clock.next(1000),1400);
 clock.setQuantize('bar');
 assert.equal(clock.interval(),1600);
 assert.equal(clock.next(1001),2600);
 clock.reset(4000);
 assert.equal(clock.next(4000),5600);
 const taps=Beat.createClock();
 assert.equal(taps.tap(1000),null);
 assert.equal(taps.tap(1400),null);
 assert.equal(taps.tap(1800),150);
 assert.equal(taps.bpm,150);
 assert.equal(taps.origin,1800);
 assert.equal(taps.tap(2200),150);
 assert.equal(taps.tap(4900),null);
 assert.equal(taps.tap(5300),null);
 assert.equal(taps.tap(5700),150);
});
test('tap rejects accidental rapid input and ignores invalid timestamps',()=>{
 const clock=Beat.createClock({bpm:120});
 assert.equal(clock.tap(NaN),null);
 assert.equal(clock.tap(0),null);
 assert.equal(clock.tap(100),null);
 assert.equal(clock.tap(600),null);
 assert.equal(clock.tap(1100),120);
 assert.equal(clock.tap(1600),120);
 assert.equal(clock.tap(2100),120);
 assert.equal(clock.setBpm(0,2500),40);
 assert.equal(clock.tap(2900),null);
});
