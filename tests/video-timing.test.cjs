'use strict';
const test=require('node:test');
const assert=require('node:assert/strict');
const Timing=require('../src/video-timing.js');
const C=require('../src/composition.js');
const id='media-11111111-2222-4333-8444-555555555555.webm';
test('video timing defaults, In/Out and loop normalization',()=>{
 assert.deepEqual(Timing.normalizePlayback(),{loop:true,inPoint:0,outPoint:null});
 assert.deepEqual(Timing.normalizePlayback({loop:false,inPoint:.25,outPoint:1.25}),{loop:false,inPoint:.25,outPoint:1.25});
 assert.deepEqual(Timing.normalizePlayback({loop:'false',inPoint:-5,outPoint:0}),{loop:true,inPoint:0,outPoint:null});
 assert.deepEqual(Timing.normalizePlayback({loop:false,inPoint:3,outPoint:2}),{loop:false,inPoint:3,outPoint:null});
 assert.deepEqual(Timing.normalizePlayback({loop:false,inPoint:Infinity,outPoint:NaN}),{loop:false,inPoint:0,outPoint:null});
 assert.equal(Timing.bounds({inPoint:.2,outPoint:1.2},1.625).start,.2);
 assert.equal(Timing.bounds({inPoint:.2,outPoint:1.2},1.625).end,1.2);
 assert.equal(Timing.bounds({inPoint:.2,outPoint:9},1.625).end,1.625);
 assert.equal(Timing.bounds({inPoint:9,outPoint:null},1.625).start,1.575);
 assert.equal(Timing.seekTime(0,{inPoint:.2,outPoint:.8},1.625),.2);
 assert.equal(Timing.seekTime(9,{inPoint:.2,outPoint:.8},1.625),.8);
 assert.equal(Timing.atOut(.77,{inPoint:.2,outPoint:.8},1.625),true);
 assert.equal(Timing.atOut(.6,{inPoint:.2,outPoint:.8},1.625),false);
 assert.equal(Timing.atOut(.7,{inPoint:.2,outPoint:.8},NaN),false);
 assert.equal(Timing.formatTime(65.9),'01:05.9');
 assert.equal(Timing.formatTime(0),'00:00.0');
});
test('old imported video clips default to looping and preserve FX, transforms and metadata',()=>{
 let c=C.putMediaClip(C.createComposition(),2,5,{id,name:'video.webm'});
 let clip=c.layers[2].clips[5];
 assert.equal(clip.mediaId,id);assert.deepEqual(clip.playback,Timing.DEFAULT_PLAYBACK);
 c=C.updateClipParams(c,2,5,{speed:1.5,scale:1.25,rotation:30});
 c=C.setClipEffects(c,2,5,[{id:'fx-011',wet:.45}]);
 c=C.setMediaPlayback(c,2,5,{loop:false,inPoint:.2,outPoint:1.2});
 clip=c.layers[2].clips[5];
 assert.equal(clip.playback.loop,false);
 assert.equal(clip.playback.inPoint,.2);assert.equal(clip.playback.outPoint,1.2);
 assert.equal(clip.params.speed,1.5);assert.equal(clip.fxStack.length,1);
 const restored=C.normalize(JSON.parse(JSON.stringify(c)));
 assert.deepEqual(restored.layers[2].clips[5],clip);
 const copied=C.pasteClip(restored,3,4,C.getClip(restored,2,5));
 assert.deepEqual(copied.layers[3].clips[4].playback,clip.playback);
 assert.equal(copied.layers[3].clips[4].params.speed,1.5);
});
test('video timing is independent per clip and follows move and duplication',()=>{
 let c=C.createComposition();
 c=C.putMediaClip(c,0,5,{id,name:'one.webm'});
 c=C.putMediaClip(c,1,4,{id,name:'two.webm'});
 c=C.setMediaPlayback(c,0,5,{loop:false,inPoint:.4,outPoint:.9});
 c=C.setMediaPlayback(c,1,4,{loop:true,inPoint:.1,outPoint:1.3});
 assert.equal(c.layers[0].clips[5].playback.loop,false);
 assert.equal(c.layers[1].clips[4].playback.loop,true);
 c=C.duplicateClip(c,0,5);
 assert.deepEqual(c.layers[0].clips[6].playback,c.layers[0].clips[5].playback);
 c=C.moveClip(c,0,5,2,6);
 assert.equal(c.layers[2].clips[6].playback.inPoint,.4);
 assert.equal(c.layers[1].clips[4].playback.inPoint,.1);
 c=C.setMediaPlayback(c,2,6,{outPoint:null});
 assert.equal(c.layers[2].clips[6].playback.outPoint,null);
 assert.equal(c.layers[0].clips[6].playback.outPoint,.9);
});
test('invalid time modifications cannot corrupt videos or non-video generators',()=>{
 let c=C.createComposition();
 const before=C.normalize(c);
 c=C.setMediaPlayback(c,0,0,{loop:false,inPoint:90});
 assert.deepEqual(c,before);
 c=C.putMediaClip(c,1,7,{id,name:'video.webm'});
 c=C.setMediaPlayback(c,1,7,{inPoint:Infinity,outPoint:'eval()',loop:'evil'});
 assert.deepEqual(c.layers[1].clips[7].playback,Timing.DEFAULT_PLAYBACK);
 assert.equal(C.activeLayers(C.launch(c,1,7)).find(x=>x.index===1).playback.loop,true);
});
